import type { ApiWorkflow } from "./types.js";

export interface OutputImage {
  filename: string;
  subfolder: string;
  type: string;
}

interface QueueResponse {
  prompt_id: string;
}

interface HistoryEntry {
  outputs?: Record<string, { images?: OutputImage[] }>;
  status?: { status_str?: string; messages?: [string, { exception_message?: string }][] };
}

type HistoryResponse = Record<string, HistoryEntry>;

/** Sends the workflow to the ComfyUI queue and returns the prompt ID. */
export async function queuePrompt(baseUrl: string, workflow: ApiWorkflow): Promise<string> {
  const response = await fetch(`${baseUrl}/prompt`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ prompt: workflow, client_id: crypto.randomUUID() }),
  });

  if (!response.ok) {
    throw new Error(`ComfyUI rejected the prompt: ${response.status} ${await response.text()}`);
  }

  const data = (await response.json()) as QueueResponse;
  return data.prompt_id;
}

/** Waits for the prompt to finish and returns the generated images (polls /history). */
export async function pollForOutputImages(
  baseUrl: string,
  promptId: string,
  options: { intervalMs?: number; timeoutMs?: number } = {},
): Promise<OutputImage[]> {
  const intervalMs = options.intervalMs ?? 2000;
  const timeoutMs = options.timeoutMs ?? 5 * 60 * 1000;
  const deadline = Date.now() + timeoutMs;

  while (Date.now() < deadline) {
    const images = await fetchHistoryOutputImages(baseUrl, promptId);
    if (images) {
      return images;
    }
    await sleep(intervalMs);
  }

  throw new Error(`Timed out waiting for prompt ${promptId}`);
}

async function fetchHistoryOutputImages(
  baseUrl: string,
  promptId: string,
): Promise<OutputImage[] | null> {
  const response = await fetch(`${baseUrl}/history/${promptId}`);
  if (!response.ok) {
    throw new Error(`ComfyUI rejected /history: ${response.status}`);
  }

  const history = (await response.json()) as HistoryResponse;
  const entry = history[promptId];
  if (!entry) {
    return null;
  }
  if (entry.status?.status_str === "error") {
    throw new Error(`ComfyUI failed on prompt ${promptId}: ${executionErrorMessage(entry)}`);
  }

  const images = Object.values(entry.outputs ?? {}).flatMap((output) => output.images ?? []);
  return images.length > 0 ? images : null;
}

function executionErrorMessage(entry: HistoryEntry): string {
  const error = entry.status?.messages?.find(([type]) => type === "execution_error");
  return error?.[1].exception_message ?? "unknown error";
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/** Downloads the bytes of an output image already generated by ComfyUI. */
export async function downloadImage(baseUrl: string, image: OutputImage): Promise<Buffer> {
  const query = new URLSearchParams({
    filename: image.filename,
    subfolder: image.subfolder,
    type: image.type,
  });

  const response = await fetch(`${baseUrl}/view?${query.toString()}`);
  if (!response.ok) {
    throw new Error(`ComfyUI rejected /view: ${response.status}`);
  }

  return Buffer.from(await response.arrayBuffer());
}
